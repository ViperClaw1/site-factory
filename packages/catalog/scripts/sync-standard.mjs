// Vendors the catalog standard from Path-platform-standards and rebuilds the reference
// reports with the standard's own checker (catalog.py), so the TypeScript port is tested
// against what the people filling the file actually see.
//
//   node scripts/sync-standard.mjs [path/to/Path-platform-standards]          copy + rebuild
//   node scripts/sync-standard.mjs --check [path/to/Path-platform-standards]  compare only
//
// The standards repository defaults to a sibling of site-factory. --check needs no Python
// and never fails the run: a drift is printed as a GitHub Actions warning.
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const STANDARD_DIR = join(PKG, "standard");
const EXPECTED_DIR = join(STANDARD_DIR, "expected");
const TEMPLATE_PATH = "05-templates/catalog";

// Files copied verbatim. Anything else in the template folder (xlsx, feed.py, docs) is not
// part of the contract this package implements.
const FILES = ["catalog.schema.json", "categories.csv", "example.json", "catalog.csv", "translations.csv", "changes.csv"];

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const standardsRoot = resolve(args.find((arg) => !arg.startsWith("--")) ?? process.env.STANDARDS_DIR ?? join(PKG, "../../../Path-platform-standards"));
const templateDir = join(standardsRoot, TEMPLATE_PATH);

// CRLF from Python's csv writer vs LF after a git checkout must not count as a change.
const normalized = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");

function git(...gitArgs) {
  const result = spawnSync("git", ["-C", standardsRoot, ...gitArgs], { encoding: "utf8" });
  return result.status === 0 ? result.stdout.trim() : "";
}

if (!existsSync(join(templateDir, "catalog.py"))) {
  const message = `catalog standard not found at ${templateDir}`;
  if (checkOnly) {
    console.log(`::warning::${message}; drift check skipped`);
    process.exit(0);
  }
  console.error(message);
  process.exit(1);
}

// --- Drift check -------------------------------------------------------------
// Compares the vendored copy with the standards checkout and reports what changed.
if (checkOnly) {
  const changed = FILES.filter((file) => normalized(join(templateDir, file)) !== normalized(join(STANDARD_DIR, file)));
  const head = git("log", "-1", "--format=%h %cs %s", "--", TEMPLATE_PATH) || "unknown";
  if (changed.length === 0) {
    console.log(`packages/catalog/standard matches the standard (${head})`);
  } else {
    console.log(
      `::warning::packages/catalog/standard is behind the catalog standard: ${changed.join(", ")} differ. ` +
        `Latest standard commit: ${head}. Run pnpm --filter @repo/catalog sync-standard and review the diff.`,
    );
  }
  process.exit(0);
}

// --- Copy --------------------------------------------------------------------
mkdirSync(EXPECTED_DIR, { recursive: true });
mkdirSync(join(PKG, "src"), { recursive: true });
for (const file of FILES) copyFileSync(join(templateDir, file), join(STANDARD_DIR, file));

// categories.csv is embedded as text so the package works in the browser without fs.
writeFileSync(
  join(PKG, "src/categories.generated.ts"),
  "// Generated by scripts/sync-standard.mjs from standard/categories.csv. Do not edit.\n" +
    `export const CATEGORIES_CSV = ${JSON.stringify(readFileSync(join(STANDARD_DIR, "categories.csv"), "utf8"))};\n`,
);

// --- Reference reports from catalog.py ---------------------------------------
function python() {
  if (process.env.PYTHON) return [process.env.PYTHON];
  return process.platform === "win32" ? ["py", "-3"] : ["python3"];
}

function runCatalogPy(commandArgs) {
  const [exe, ...pre] = python();
  const result = spawnSync(exe, [...pre, join(templateDir, "catalog.py"), ...commandArgs], {
    cwd: PKG,
    encoding: "utf8",
    env: { ...process.env, PYTHONIOENCODING: "utf-8" },
  });
  if (result.error || (result.status !== 0 && result.status !== 1)) {
    console.error(result.error?.message ?? result.stderr);
    process.exit(1);
  }
  return result.stdout.replace(/\r\n/g, "\n");
}

const fixtures = JSON.parse(readFileSync(join(PKG, "fixtures/fixtures.json"), "utf8"));
for (const fixture of fixtures) {
  const options = fixture.catalog ? ["--catalog", fixture.catalog, "--mode", fixture.mode] : [];
  writeFileSync(join(EXPECTED_DIR, `${fixture.name}.txt`), runCatalogPy(["check", ...fixture.files, ...options]));
}

// CSV -> JSON as catalog.py does it. Not example.json: catalog.py reads attributes as strings.
runCatalogPy([
  "csv2json",
  "standard/catalog.csv",
  "standard/translations.csv",
  "--catalog",
  "example-store",
  "--mode",
  "replace",
  "-o",
  "standard/expected/example-csv2json.json",
]);

// --- Provenance --------------------------------------------------------------
const commit = git("rev-parse", "HEAD") || "unknown";
const dirty = git("status", "--porcelain", "--", TEMPLATE_PATH) ? " (with uncommitted changes)" : "";
writeFileSync(
  join(STANDARD_DIR, "SOURCE.md"),
  `# Source of this copy

Vendored from \`Path-platform-standards/${TEMPLATE_PATH}\`, commit \`${commit}\`${dirty}.
Synced ${new Date().toISOString().slice(0, 10)}. Do not edit these files by hand.

Files: ${FILES.map((file) => `\`${file}\``).join(", ")}.

\`expected/\` holds the output of \`catalog.py\` from the same commit: \`check\` on every
fixture in \`../fixtures/fixtures.json\` and \`csv2json\` of \`catalog.csv\` + \`translations.csv\`.

Update after a change in the standard:

\`\`\`bash
pnpm --filter @repo/catalog sync-standard [path/to/Path-platform-standards]
pnpm --filter @repo/catalog test
\`\`\`
`,
);

console.log(`Synced ${FILES.length} files and ${fixtures.length} reference reports from ${commit.slice(0, 7)}${dirty}`);
